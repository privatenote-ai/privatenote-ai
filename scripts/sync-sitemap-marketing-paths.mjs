/**
 * Replace blog post URLs in sitemap.xml from PUBLIC_MARKETING_PATHS.
 * Keeps non-blog entries unchanged.
 *
 * Usage: npx tsx scripts/sync-sitemap-marketing-paths.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PUBLIC_MARKETING_PATHS } from "../shared/publicMarketingPaths.ts";
import { PUBLIC_SITE_ORIGIN } from "../shared/homeSeoLinks.ts";
import { isLocaleHomeSegment } from "../shared/supportedLanguages.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SITEMAP = path.join(__dirname, "../client/public/sitemap.xml");

function sitemapLocForRoute(route) {
  if (route === "/") return `${PUBLIC_SITE_ORIGIN}/`;
  if (/^\/[^/]+$/.test(route) && isLocaleHomeSegment(route.slice(1))) {
    return `${PUBLIC_SITE_ORIGIN}${route}/`;
  }
  return `${PUBLIC_SITE_ORIGIN}${route}`;
}

function urlBlock(route, lastmod = "2026-07-03") {
  return `  <url><loc>${sitemapLocForRoute(route)}</loc><lastmod>${lastmod}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>`;
}

const BLOG_SECTION_MARKER =
  "  <!-- Blog posts (generated by scripts/sync-sitemap-marketing-paths.mjs) -->";

function stripBlogEntries(xml) {
  let cleaned = xml;

  // Single-line blog <url> entries.
  cleaned = cleaned.replace(/^  <url><loc>[^<]*\/blog\/[^<]*<\/loc>.*<\/url>\n?/gm, "");

  // Multiline blog <url> entries.
  cleaned = cleaned.replace(
    /  <url>\s*\n\s*<loc>[^<]*\/blog\/[^<]*<\/loc>[\s\S]*?<\/url>\n?/g,
    "",
  );

  // Broken leftovers from prior line-based stripping (missing <loc>).
  cleaned = cleaned.replace(/  <url>\s*\n\s*<lastmod>[\s\S]*?<\/url>\n?/g, "");

  // Orphan <loc> lines inserted between <url> blocks by locale extension.
  cleaned = cleaned.replace(
    /<\/url>\n\s+<loc>https:\/\/privatenote\.ai\/[^<]+\/<\/loc>\n(?=\s*<url>)/g,
    "</url>\n",
  );

  // Remove previously generated blog section markers.
  cleaned = cleaned.replace(
    new RegExp(`\\n*${BLOG_SECTION_MARKER.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\n*`, "g"),
    "\n",
  );

  return cleaned.replace(/\n{3,}/g, "\n\n");
}

async function main() {
  const blogRoutes = PUBLIC_MARKETING_PATHS.filter((route) => route.includes("/blog/")).sort();
  const xml = await fs.readFile(SITEMAP, "utf8");

  const withoutBlog = stripBlogEntries(xml);

  const blogSection = ["", BLOG_SECTION_MARKER, ...blogRoutes.map((route) => urlBlock(route)), ""].join(
    "\n",
  );

  const closingIndex = withoutBlog.lastIndexOf("</urlset>");
  if (closingIndex === -1) {
    throw new Error("Missing </urlset> in sitemap");
  }

  const updated = `${withoutBlog.slice(0, closingIndex).trimEnd()}\n${blogSection}\n</urlset>\n`;
  await fs.writeFile(SITEMAP, updated, "utf8");
  console.log(`Updated ${SITEMAP} with ${blogRoutes.length} blog routes`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
